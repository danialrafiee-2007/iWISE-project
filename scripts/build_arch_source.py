"""Writes the real code behind the Architecture page's graph (D-206) into static_html/js/arch-src.js.

Every node of js/arch-data.js names its code with `src`: "file.py:name" (a function or class of
src/truth_guardian/file.py, read with the parse tree, exactly as it is in the file), "file.py" (the module's overview:
its docstring and the signatures of its public functions and classes), or "js/arch-graph.js:name" (a function of the
graph's own script, for the graph that explains itself). Run it after changing a file the graph shows;
tests/test_html_ui.py fails while the page's copy differs from the code.

    uv run python scripts/build_arch_source.py
"""

import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src" / "truth_guardian"
STATIC = PACKAGE / "web" / "static_html"
DATA = STATIC / "js" / "arch-data.js"
OUT = STATIC / "js" / "arch-src.js"
HEAD = """// Generated by scripts/build_arch_source.py from the source files: the real code behind each node of the Architecture
// page's graph (js/arch-data.js). Do not edit; run the script again after changing a file it shows.
"""


def keys(data: str = "") -> list[str]:
    return sorted(set(re.findall(r'src: "([^"]+)"', data or DATA.read_text(encoding="utf-8"))))


def _python(path: Path, name: str | None) -> str:
    text = path.read_text(encoding="utf-8")
    tree = ast.parse(text)
    if name is None:
        lines = [f'"""{ast.get_docstring(tree) or ""}"""', ""]
        for node in tree.body:
            if isinstance(node, ast.FunctionDef | ast.ClassDef) and not node.name.startswith("_"):
                head = ast.get_source_segment(text, node).splitlines()
                signature = next(line for line in head if line.lstrip().startswith(("def ", "class "))).rstrip()
                lines.append(signature + " ...")
        return "\n".join(lines)
    for node in tree.body:
        if isinstance(node, ast.FunctionDef | ast.ClassDef) and node.name == name:
            start = min([node.lineno] + [d.lineno for d in node.decorator_list])
            return "\n".join(text.splitlines()[start - 1 : node.end_lineno])
    raise KeyError(f"{path.name} has no top-level {name}")


def _javascript(path: Path, name: str) -> str:
    """A named function of a script, from its line to its closing brace (the script keeps its braces balanced)."""
    lines = path.read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines):
        if re.match(rf"\s*function {re.escape(name)}\(", line):
            indent = len(line) - len(line.lstrip())
            depth = 0
            for j in range(i, len(lines)):
                depth += lines[j].count("{") - lines[j].count("}")
                if depth <= 0 and j > i or (depth == 0 and lines[j].rstrip().endswith("}")):
                    return "\n".join(row[indent:] if row[:indent].strip() == "" else row for row in lines[i : j + 1])
    raise KeyError(f"{path.name} has no function {name}")


def source(key: str) -> str:
    file, _, name = key.partition(":")
    if file.startswith("js/"):
        return _javascript(STATIC / file, name)
    return _python(PACKAGE / file, name or None)


def build() -> str:
    found = {key: source(key) for key in keys()}
    return HEAD + "window.TG_SRC = " + json.dumps(found, ensure_ascii=False, indent=0) + ";\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(keys())} pieces of code)", file=sys.stderr)
