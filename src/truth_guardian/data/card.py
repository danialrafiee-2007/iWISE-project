"""Generate the data card (docs/DATA_CARD.md) from processed samples."""

from collections import Counter
from statistics import mean

from truth_guardian.schema import Sample


def _words(text: str) -> int:
    return len(text.split())


def _pct(part: int, total: int) -> str:
    return f"{100 * part / total:.1f}%" if total else "-"


def _table(header: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return lines + [""]


def _overview(files: dict[str, list[Sample]]) -> list[str]:
    rows = []
    for name, samples in files.items():
        halluc = sum(s.labels.response == "hallucinated" for s in samples)
        rows.append([
            name,
            len(samples),
            len({s.meta.group_id for s in samples}),
            _pct(halluc, len(samples)),
            sum(len(s.labels.spans) for s in samples),
            round(mean(_words(s.answer) for s in samples)),
            round(mean(sum(_words(d.text) for d in s.documents) for s in samples)),
        ])
    return _table(["File", "Samples", "Groups", "Hallucinated", "Spans", "Avg answer words", "Avg context words"], rows)


def _by_task(files: dict[str, list[Sample]]) -> list[str]:
    rows = []
    for name, samples in files.items():
        for task in sorted({s.meta.task for s in samples}):
            subset = [s for s in samples if s.meta.task == task]
            halluc = sum(s.labels.response == "hallucinated" for s in subset)
            rows.append([name, task, len(subset), _pct(halluc, len(subset))])
    return _table(["File", "Task", "Samples", "Hallucinated"], rows)


def _span_labels(files: dict[str, list[Sample]]) -> list[str]:
    rows = []
    for name, samples in files.items():
        spans = [sp for s in samples for sp in s.labels.spans]
        if not spans:
            continue
        labels = Counter(sp.source_label for sp in spans)
        rows.append([
            name,
            *(labels.get(k, 0) for k in ("Evident Conflict", "Subtle Conflict", "Evident Baseless Info", "Subtle Baseless Info")),
            sum(bool(sp.implicit_true) for sp in spans),
            sum(bool(sp.due_to_null) for sp in spans),
        ])
    return _table(["File", "Evident Conflict", "Subtle Conflict", "Evident Baseless", "Subtle Baseless", "implicit_true", "due_to_null"], rows)


def _quality(files: dict[str, list[Sample]]) -> list[str]:
    rows = []
    for name, samples in files.items():
        counts = Counter(s.meta.quality for s in samples)
        if set(counts) != {"good"}:
            rows.append([name, *(counts.get(k, 0) for k in ("good", "incorrect_refusal", "truncated"))])
    return _table(["File", "good", "incorrect_refusal", "truncated"], rows)


def _length_shortcut(files: dict[str, list[Sample]]) -> list[str]:
    rows = []
    for name, samples in files.items():
        if not name.startswith("halueval"):
            continue
        right = [_words(s.answer) for s in samples if s.labels.response == "grounded"]
        wrong = [_words(s.answer) for s in samples if s.labels.response == "hallucinated"]
        rows.append([name, f"{mean(right):.1f}", f"{mean(wrong):.1f}"])
    return _table(["File", "Avg words (grounded)", "Avg words (hallucinated)"], rows)


def render_card(files: dict[str, list[Sample]], provenance: list[str]) -> str:
    lines = [
        "# Data Card",
        "",
        "Generated by `scripts/build_data.py`. Do not edit by hand.",
        "",
        "## Provenance",
        "",
        *[f"- {p}" for p in provenance],
        "",
        "## Overview",
        "",
        *_overview(files),
        "## Hallucination rate by task",
        "",
        *_by_task(files),
        "## RAGTruth span labels",
        "",
        *_span_labels(files),
        "## Response quality (excluded from training, reported separately)",
        "",
        *_quality(files),
        "## Length shortcut check (HaluEval)",
        "",
        "A large gap means answer length alone could reveal the label; models must not rely on it.",
        "",
        *_length_shortcut(files),
    ]
    return "\n".join(lines)
